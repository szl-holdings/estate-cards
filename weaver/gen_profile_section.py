"""Generate the profile README section (idempotent, marker-bounded) from audit-latest."""
import json
import os

ROOT = 'C:/SZL/edge-debug/estate-cards'
audit = json.load(open(os.path.join(ROOT, 'data', 'audit-latest.json'), encoding='utf-8'))
ts = audit['generated_at']
m, d, s = audit['hf_models']['total'], audit['hf_datasets']['total'], audit['hf_spaces']['total']
gh = audit['gh']['total']
prs = audit.get('gh_prs', {}).get('open_prs')
mesh_n = len(audit.get('mesh', {}).get('files', []))
sr = (audit.get('space_runtime') or {}).get('stages', {})
running = sum(1 for v in sr.values() if v == 'RUNNING')

rows = []
rows.append('<!-- szl:estate-cards:v1 generated %s -->' % ts)
rows.append('')
rows.append('## Estate at a glance (measured %s UTC)' % ts)
rows.append('')
rows.append('An automated, receipt-honest audit snapshot. Every number below was measured at capture time from the platform APIs; badges and graphs are generated by [estate-cards](https://github.com/szl-holdings/estate-cards), the estate card weaver (stdlib Python, deterministic SVG, KANCHAY palette).')
rows.append('')
rows.append('- **%d GitHub repositories** in this org (canonical source).' % gh)
rows.append('- **%d models, %d datasets, %d Spaces** on [Hugging Face](https://huggingface.co/SZLHOLDINGS) - fully public for showcase (%d Spaces measured RUNNING at capture; 1 governance dataset held private).' % (m, d, s, running))
rows.append('- **%d receipt files** in the khipu-scholar-runs mesh ledger at capture.' % mesh_n)
if prs is not None:
    rows.append('- **%d open PRs** estate-wide at capture.' % prs)
rows.append('- Every HF repo is getting a showcase card with real graphs, rolled out at a safe pace; see the [rollout receipts](https://github.com/szl-holdings/estate-cards/blob/main/rollout_receipts.jsonl).')
rows.append('')
rows.append('<p><img src="assets/graphs/org-fleet.svg" alt="Estate artifact census" width="420" /> <img src="assets/graphs/org-spaces.svg" alt="Space runtime stages" width="420" /></p>')
rows.append('')
rows.append('<p><img src="assets/graphs/org-mesh.svg" alt="Mesh receipt families" width="720" /></p>')
rows.append('')
rows.append('<!-- /szl:estate-cards:v1 -->')
open(os.path.join(ROOT, 'data', 'profile_section.md'), 'w', encoding='utf-8').write(chr(10).join(rows))
print('SECTION_WRITTEN models', m, 'datasets', d, 'spaces', s, 'gh', gh, 'prs', prs, 'mesh', mesh_n, 'running', running)
