"""Card renderers: top-tech-company-grade, receipt-honest cards for HF repos.

Rules (estate doctrine):
- never delete existing README content; append a clearly-marked showcase section,
  or compose a fresh card only when no real README exists.
- every number carries MEASURED/REPORTED/UNKNOWN + source + UTC.
- charts are deterministic stdlib SVG committed alongside the card.
"""
import hashlib
import json
import os
import re
import urllib.error
import urllib.request
import datetime

from weaver import charts
from weaver import policy
from weaver import source_guard

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README_MAX_BYTES = 512_000
CARD_MARK = '<!-- szl:showcase-card v1'


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def fetch_readme(repo_id, repo_type, *, parent_revision):
    """Read immutable public README bytes; ambiguity is HOLD, never empty-card permission."""
    # Model repositories live at /<org>/<model>, unlike datasets and Spaces.
    # Preserve the immutable parentCommit from the source-ownership preflight.
    kinds = {'model': '', 'dataset': 'datasets/', 'space': 'spaces/'}
    if (
        repo_type not in kinds or not isinstance(repo_id, str)
        or not source_guard.REPO_ID.fullmatch(repo_id)
        or not isinstance(parent_revision, str)
        or not source_guard.SHA40.fullmatch(parent_revision)
    ):
        raise source_guard.Hold('README_SOURCE_IDENTITY_INVALID')
    url = 'https://huggingface.co/%s%s/raw/%s/README.md' % (
        kinds[repo_type], repo_id, parent_revision
    )
    req = urllib.request.Request(url, headers={'User-Agent': 'SZL-card-public-readback/1'})
    try:
        with urllib.request.urlopen(req, timeout=12) as response:
            if response.status != 200:
                raise source_guard.Hold('README_HTTP_NOT_OK')
            # A 200 HTML error page cannot become a new canonical README.
            content_type = response.headers.get('Content-Type', '')
            if not isinstance(content_type, str) or not content_type.lower().startswith('text/plain'):
                raise source_guard.Hold('README_NON_TEXT')
            raw = response.read(README_MAX_BYTES + 1)
    except source_guard.Hold:
        raise
    except urllib.error.HTTPError:
        raise source_guard.Hold('README_HTTP_UNAVAILABLE') from None
    except Exception:
        raise source_guard.Hold('README_TRANSPORT_UNAVAILABLE') from None
    if not raw or len(raw) > README_MAX_BYTES:
        raise source_guard.Hold('README_SIZE_INVALID')
    try:
        return raw.decode('utf-8', 'strict')
    except UnicodeError:
        raise source_guard.Hold('README_NOT_UTF8') from None


def _badge(label, value, color):
    return '![%s](https://img.shields.io/badge/%s-%s-%s?style=flat-square)' % (
        label, label.replace('-', '--'), str(value).replace('-', '--').replace('_', '_'), color)


def _footer(kind, repo_id, ts, extra=''):
    body = CARD_MARK + ' generated %s by szl-holdings/estate-cards weaver v0.1.0 -->' % ts
    sha = hashlib.sha256((repo_id + '|' + ts + '|' + extra).encode()).hexdigest()[:16]
    body += '\n\n<sub>Generated by the [estate-cards weaver](https://github.com/szl-holdings/estate-cards) '
    body += '(stdlib Python, deterministic SVG, KANCHAY palette). '
    body += 'Numbers labeled MEASURED/REPORTED/UNKNOWN with capture time %s UTC; verify at source. Card id %s.</sub>' % (ts, sha)
    return body


def evidence_charts(audit, repo_id):
    """Return dict {asset_name: svg} of honest charts for this repo, from audit data only."""
    out = {}
    # org context donut for every card (small, honest)
    m = audit['hf_models']['total']; d = audit['hf_datasets']['total']; s = audit['hf_spaces']['total']
    out['org-context.svg'] = charts.donut(
        [('models', m), ('datasets', d), ('spaces', s)], title='Estate artifacts (MEASURED %s)' % audit['generated_at'])
    # mesh receipts timeline facts if present
    mesh_files = audit.get('mesh', {}).get('files') or []
    if mesh_files:
        fam = {}
        for f in mesh_files:
            key = os.path.basename(f).split('-20')[0].split('-v1')[0][:34]
            fam[key] = fam.get(key, 0) + 1
        top = sorted(fam.items(), key=lambda kv: -kv[1])[:12]
        out['mesh-receipts.svg'] = charts.hbar([(k, v) for k, v in top],
                                               title='Receipt families on khipu-scholar-runs mesh/ (MEASURED)')
    return out


def model_card(repo_id, audit, meta_extra=None):
    ts = now()
    charts_assets = evidence_charts(audit, repo_id)
    kind = 'model'
    src = policy.source_for(repo_id)
    name = repo_id.split('/')[-1]
    body = []
    body.append('# %s' % name.replace('-', ' '))
    body.append('')
    body.append('Part of the [SZL Holdings](https://huggingface.co/SZLHOLDINGS) governed-AI estate: source-linked models, datasets and Spaces with receipted, checkable results.')
    body.append('')
    body.append('%s %s' % (_badge('estate', 'SZLHOLDINGS', '%23030F29'),
                            _badge('kind', kind, '168f89')))
    body.append('')
    body.append('## Identity')
    body.append('')
    body.append('- **Repo:** [%s](https://huggingface.co/%s)' % (repo_id, repo_id))
    body.append('- **Canonical source:** [%s](%s)' % (src.split('/')[-1] if '/szl-holdings/' in src else 'szl-holdings org', src))
    body.append('- **Kind:** %s (trained artifact in the governed factory)' % kind)
    if meta_extra:
        for k, v in meta_extra.items():
            body.append('- **%s:** %s' % (k, v))
    body.append('')
    body.append('## Evidence')
    body.append('')
    if charts_assets:
        body.append('<p><img src="assets/szl-card/org-context.svg" alt="Estate context" width="420" /></p>')
        body.append('<p><img src="assets/szl-card/mesh-receipts.svg" alt="Receipt families" width="720" /></p>')
        body.append('')
        body.append('Charts are deterministic stdlib SVG generated from the audit snapshot '
                    '(%s, MEASURED). Where this repo lacks a measured curve, we say UNKNOWN rather than invent one.' % audit['generated_at'])
    body.append('')
    body.append('## Honesty')
    body.append('')
    body.append('- Training/eval claims for this artifact live in its receipt files (see the estate mesh); anything not receipted here is UNKNOWN.')
    body.append('- No benchmark number is asserted on this card beyond what a dated audit measured.')
    body.append('')
    return '\n'.join(body), charts_assets


def dataset_card(repo_id, audit, purpose=None):
    ts = now()
    charts_assets = evidence_charts(audit, repo_id)
    src = policy.source_for(repo_id)
    name = repo_id.split('/')[-1]
    body = []
    body.append('# %s' % name.replace('-', ' '))
    body.append('')
    body.append('A receipt-bearing dataset of the [SZL Holdings](https://huggingface.co/SZLHOLDINGS) estate: '
                'every artifact family carries its dated audit and source links.')
    body.append('')
    if purpose:
        body.append(purpose)
        body.append('')
    body.append('- **Repo:** [%s](https://huggingface.co/%s)' % (repo_id, repo_id))
    body.append('- **Canonical source:** %s' % src)
    body.append('')
    if charts_assets:
        body.append('<p><img src="assets/szl-card/mesh-receipts.svg" alt="Receipt families" width="720" /></p>')
        body.append('')
    return '\n'.join(body), charts_assets


def space_card(repo_id, audit, purpose=None):
    return dataset_card(repo_id, audit, purpose)


def build_card(kind, repo_id, audit, current_readme, purpose=None, meta_extra=None):
    """Return (readme_content, assets_dict, mode). mode: compose|append|skip-fresh."""
    ts = now()
    if kind == 'model':
        fresh, assets = model_card(repo_id, audit, meta_extra)
    elif kind == 'dataset':
        fresh, assets = dataset_card(repo_id, audit, purpose)
    else:
        fresh, assets = space_card(repo_id, audit, purpose)
    footer = _footer(kind, repo_id, ts)
    if current_readme and len(current_readme.strip()) > 500 and CARD_MARK not in current_readme:
        # curated README exists: append a clearly-marked showcase section, never delete
        section = '\n\n---\n\n## SZL estate showcase card\n\n' + fresh + '\n' + footer
        out = current_readme.rstrip() + '\n' + section
        # strip the duplicated top title from the appended copy
        return out, assets, 'append'
    if current_readme and CARD_MARK in current_readme:
        # replace previous showcase section between markers
        pre = current_readme.split(CARD_MARK)[0].rstrip()
        return pre + '\n\n---\n\n## SZL estate showcase card\n\n' + fresh + '\n' + footer, assets, 'replace-marked'
    # no real README: compose fresh (preserve YAML front-matter if any)
    fm = ''
    if current_readme and current_readme.lstrip().startswith('---'):
        parts = current_readme.split('---')
        if len(parts) >= 3:
            fm = '---' + parts[1] + '---\n\n'
    return fm + fresh + '\n' + footer, assets, 'compose'
